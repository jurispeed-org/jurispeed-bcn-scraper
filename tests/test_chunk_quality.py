def test_force_status_consistency(all_docs):
    for filepath, doc in all_docs:
        for chunk in doc["chunks"]:
            meta = chunk["metadata"]
            idx = chunk["chunk_index"]
            if meta.get("force_status") == "active":
                assert meta.get("in_force") is True, \
                    f"{filepath}: chunk {idx} force_status=active but in_force={meta.get('in_force')}"
            elif meta.get("force_status") in ("repealed", "deferred"):
                assert meta.get("in_force") is False, \
                    f"{filepath}: chunk {idx} force_status={meta['force_status']} but in_force={meta.get('in_force')}"


def test_removed_fields_not_present(all_docs):
    for filepath, doc in all_docs:
        for chunk in doc["chunks"]:
            meta = chunk["metadata"]
            present = REMOVED_METADATA_FIELDS & set(meta.keys())
            assert not present, \
                f"{filepath}: chunk {chunk['chunk_index']} still has removed fields: {present}"


def _strip_notes(text: str) -> str:
    text = re.sub(r'\[Fragmento[^\]]*\]\n*', '', text)
    text = re.sub(r'\[Parte[^\]]*\]\n*', '', text)
    text = re.sub(r'\[Texto final[^\]]*\]\n*', '', text)
    text = re.sub(r'\[NOTA:[^\]]*\]', '', text)
    return text


def _body_without_header(content: str) -> str:
    if "\n\n" in content:
        return content.split("\n\n", 1)[1]
    if "\n" in content:
        return content.split("\n", 1)[1]
    return content


def test_article_count_matches_xml(all_docs):
    """
    Counts real articles (regular + transitory) that the XML parser's hierarchy
    extraction identifies in the original BCN XML -- excluding section-heading
    containers that merely wrap real articles as children (e.g. a "DISPOSICIONES
    TRANSITORIAS" divider) -- and compares against the distinct articles
    represented in the chunk JSON (by part_id). Catches whole articles silently
    dropped during chunking (e.g. skipped between two chunk_index values) that
    per-article content checks can't see, since those only compare articles that
    already made it into a chunk.
    """
    from core.xml_parser import BCNXMLParser

    parser = BCNXMLParser()

    for filepath, doc in all_docs:
        norm_id = doc["norm_id"]
        xml_path = f"{XMLS_DIR}/norm_{norm_id}.xml"
        if not os.path.exists(xml_path):
            pytest.skip(f"No XML available for norm {norm_id} to cross-check against")
            continue

        with open(xml_path, "r", encoding="utf-8") as fh:
            xml_content = fh.read()

        hierarchy = parser.extract_article_hierarchy(xml_content, norm_id)
        xml_article_ids = set(hierarchy.keys())

        json_part_ids = {
            chunk["metadata"].get("part_id")
            for chunk in doc["chunks"]
            if chunk["metadata"].get("part_id") is not None
        }
        # part_id may be int or str depending on serialization; normalize to str for comparison
        json_part_ids = {str(pid) for pid in json_part_ids}

        missing = xml_article_ids - json_part_ids
        # Treaty annexes with detectable per-article structure are split by the chunker
        # into synthetic sub-keys ("anexo_X_art1", "anexo_X_art2", ...) that replace the
        # single "anexo_X" hierarchy key -- that's an intentional split, not a drop.
        missing = {
            key for key in missing
            if not (key.startswith("anexo_") and any(pid.startswith(f"{key}_art") for pid in json_part_ids))
        }
        assert not missing, \
            f"{filepath}: {len(missing)} article(s) present in XML but missing from chunk JSON " \
            f"(idParte values: {sorted(missing)}) -- possible dropped article during chunking"


def test_no_content_lost_vs_original_xml(all_docs):
    """
    Reconstructs each article's full text from its chunks (in chunk_index order,
    stripping headers/fragment notes) and compares it against the article text
    extracted directly from the original BCN XML. Catches truncation/dropped
    content that per-chunk checks can't see (e.g. text before the first
    subdivision, after the last one, or a fragment silently dropped mid-split).
    """
    from core.xml_parser import BCNXMLParser

    for filepath, doc in all_docs:
        norm_id = doc["norm_id"]
        xml_path = f"{XMLS_DIR}/norm_{norm_id}.xml"
        if not os.path.exists(xml_path):
            pytest.skip(f"No XML available for norm {norm_id} to cross-check against")
            continue

        with open(xml_path, "r", encoding="utf-8") as fh:
            xml_content = fh.read()

        parser = BCNXMLParser()
        original_texts = parser.extract_article_texts(xml_content)

        groups = {}
        for chunk in doc["chunks"]:
            part_id = chunk["metadata"].get("part_id")
            if part_id is None:
                continue
            groups.setdefault(part_id, []).append(chunk)

        for part_id, group_chunks in groups.items():
            if part_id not in original_texts:
                continue
            group_sorted = sorted(group_chunks, key=lambda c: c["chunk_index"])
            reconstructed = "".join(_body_without_header(c["content"]) for c in group_sorted)
            reconstructed = _strip_notes(reconstructed)

            original_norm = re.sub(r"\s+", " ", original_texts[part_id]).strip()
            reconstructed_norm = re.sub(r"\s+", " ", reconstructed).strip()

            diff = len(original_norm) - len(reconstructed_norm)
            assert abs(diff) <= MAX_ALLOWED_RECONSTRUCTION_DIFF, \
                f"{filepath}: part_id {part_id} reconstructed text differs from original XML " \
                f"by {diff} chars (original={len(original_norm)}, reconstructed={len(reconstructed_norm)}) " \
                f"-- possible truncated/dropped content"
