"""
Chunk quality invariants for production scraper output.

Loads all bcn-*.json files generated by test_scrape_to_chunks_e2e.py and
validates structural invariants that must always hold regardless of norm type.
"""

import json
import glob
import os
import re
import sys
import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

CHUNKS_DIR = "tests/test_diverse_output/chunks"
XMLS_DIR = "tests/test_diverse_output/xmls"
REQUIRED_TOP_FIELDS = {"norm_id", "norm_type", "norm_number", "formal_citation",
                        "title", "publication_date", "official_url", "source",
                        "chunks", "total_chunks", "total_articles", "vigentes"}
VALID_FORCE_STATUS = {"active", "repealed", "deferred"}
REMOVED_METADATA_FIELDS = {"literal_text", "subdivisions", "path"}
MIN_CONTENT_AFTER_HEADER = 50  # chars
MAX_ALLOWED_RECONSTRUCTION_DIFF = 15  # chars, accounts for whitespace normalization only


def load_all_chunk_files():
    files = glob.glob(f"{CHUNKS_DIR}/bcn-*.json")
    assert len(files) > 0, f"No chunk files found in {CHUNKS_DIR}"
    results = []
    for f in files:
        with open(f, "r", encoding="utf-8") as fh:
            results.append((f, json.load(fh)))
    return results


@pytest.fixture(scope="module")
def all_docs():
    return load_all_chunk_files()


def test_top_level_schema(all_docs):
    for filepath, doc in all_docs:
        missing = REQUIRED_TOP_FIELDS - set(doc.keys())
        assert not missing, f"{filepath}: missing top-level fields: {missing}"
        assert doc["total_chunks"] == len(doc["chunks"]), \
            f"{filepath}: total_chunks={doc['total_chunks']} but len(chunks)={len(doc['chunks'])}"


def test_chunk_schema(all_docs):
    for filepath, doc in all_docs:
        for chunk in doc["chunks"]:
            assert isinstance(chunk.get("chunk_index"), int), f"{filepath}: chunk missing int chunk_index"
            assert isinstance(chunk.get("token_count"), int), f"{filepath}: chunk missing int token_count"
            assert isinstance(chunk.get("content"), str), f"{filepath}: chunk missing string content"
            assert isinstance(chunk.get("metadata"), dict), f"{filepath}: chunk missing dict metadata"


def test_no_empty_content(all_docs):
    for filepath, doc in all_docs:
        for chunk in doc["chunks"]:
            content = chunk["content"]
            assert content.strip(), \
                f"{filepath}: chunk {chunk['chunk_index']} has empty content"


def test_content_has_real_text_after_header(all_docs):
    for filepath, doc in all_docs:
        for chunk in doc["chunks"]:
            if chunk["metadata"].get("force_status") != "active":
                # Repealed/deferred articles legitimately have minimal text (e.g. "Derogado")
                continue
            content = chunk["content"]
            # Header ends at first double-newline or after first line
            # Find where actual article text starts
            if "\n\n" in content:
                body = content.split("\n\n", 1)[1]
            elif "\n" in content:
                body = content.split("\n", 1)[1]
            else:
                body = content
            assert len(body.strip()) >= MIN_CONTENT_AFTER_HEADER, \
                f"{filepath}: chunk {chunk['chunk_index']} has only header, no real content " \
                f"(body length: {len(body.strip())} chars)"


def test_no_duplicate_content(all_docs):
    for filepath, doc in all_docs:
        contents = [chunk["content"] for chunk in doc["chunks"]]
        seen = set()
        for i, c in enumerate(contents):
            assert c not in seen, \
                f"{filepath}: chunk {i} has duplicate content with earlier chunk"
            seen.add(c)


def _body_without_header(content: str) -> str:
    if "\n\n" in content:
        return content.split("\n\n", 1)[1].strip()
    if "\n" in content:
        return content.split("\n", 1)[1].strip()
    return content.strip()


def test_no_duplicate_body_content(all_docs):
    """Catches repeated article text even if headers differ (e.g. same body, different citation)."""
    for filepath, doc in all_docs:
        seen = {}
        for chunk in doc["chunks"]:
            body = _body_without_header(chunk["content"])
            if not body:
                continue
            idx = chunk["chunk_index"]
            assert body not in seen, \
                f"{filepath}: chunk {idx} has the same body content as chunk {seen[body]} (repeated text)"
            seen[body] = idx


def test_fragment_sequence_is_not_truncated(all_docs):
    """
    When a large article/subdivision is split into fragments, verify the full
    sequence is present: fragment_index values must be unique, run 1..N with no
    gaps, and match total_fragments -- a missing index means a fragment was
    silently dropped (truncated) during chunking.
    """
    for filepath, doc in all_docs:
        groups = {}
        for chunk in doc["chunks"]:
            meta = chunk["metadata"]
            if not meta.get("is_fragment"):
                continue
            key = (meta.get("part_id"), meta.get("fragment_of"))
            groups.setdefault(key, []).append(chunk)

        for key, group_chunks in groups.items():
            fragment_indices = sorted(
                c["metadata"]["fragment_index"] for c in group_chunks
                if c["metadata"].get("fragment_index") is not None
            )
            if not fragment_indices:
                continue
            total_fragments_values = {
                c["metadata"].get("total_fragments") for c in group_chunks
                if c["metadata"].get("total_fragments") is not None
            }
            assert len(total_fragments_values) <= 1, \
                f"{filepath}: fragment group {key} has inconsistent total_fragments: {total_fragments_values}"
            expected = list(range(1, len(fragment_indices) + 1))
            assert fragment_indices == expected, \
                f"{filepath}: fragment group {key} has non-sequential/missing fragment_index: {fragment_indices} " \
                f"(possible truncated/dropped fragment)"
            if total_fragments_values:
                declared_total = next(iter(total_fragments_values))
                assert declared_total == len(fragment_indices), \
                    f"{filepath}: fragment group {key} declares total_fragments={declared_total} " \
                    f"but only {len(fragment_indices)} fragments found (some may have been dropped)"


def test_chunk_index_sequential(all_docs):
    for filepath, doc in all_docs:
        indices = [chunk["chunk_index"] for chunk in doc["chunks"]]
        expected = list(range(len(doc["chunks"])))
        assert indices == expected, \
            f"{filepath}: chunk_index not sequential: got {indices[:10]}... expected {expected[:10]}..."


def test_metadata_required_fields(all_docs):
    for filepath, doc in all_docs:
        for chunk in doc["chunks"]:
            meta = chunk["metadata"]
